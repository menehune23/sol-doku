"""Extract the nine Sol glyphs as SVG paths sharing the font's common letter box."""
import json, os
from fontTools.ttLib import TTFont
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# Every Sol letter in Sol order, as Solat name -> glyph name (multi-letter Solat maps to a ligature).
ORDER = "h a e i ah u uu w o oo y ee ey ahy yoo b p d j jh t thh tth f v g k l m n r s z sh ch".split()
LETTERS = {s: "_".join(s) for s in ORDER}

font = TTFont(os.path.join(ROOT, "static", "fonts", "Sol-Regular.otf"))
gs, cmap = font.getGlyphSet(), font.getBestCmap()
glyphs, bounds = {}, []
for ch, name in LETTERS.items():
    g = gs[name]
    bp = BoundsPen(gs); g.draw(bp); bounds.append(bp.bounds)
    pp = SVGPathPen(gs, lambda v: f"{v:.1f}".rstrip("0").rstrip(".")); g.draw(pp)
    glyphs[ch] = pp.getCommands()
# Sol is monospaced: every letter shares one design box, so use the union of their bounds.
x0 = min(b[0] for b in bounds); y0 = min(b[1] for b in bounds)
x1 = max(b[2] for b in bounds); y1 = max(b[3] for b in bounds)
adv = gs["a"].width
out = {"box": [round(x0), round(-y1), round(adv - 2 * x0), round(y1 - y0)], "glyphs": glyphs}
with open(os.path.join(ROOT, "static", "sol.js"), "w") as f:
    f.write("// Generated by tools/make_sol.py from Sol-Regular.otf (github.com/menehune23/sol, SIL OFL 1.1).\n")
    f.write("window.SOL = " + json.dumps(out, separators=(",", ":")) + ";\n")
print(out["box"])
